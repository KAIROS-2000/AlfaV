from __future__ import annotations


def _lesson(
    *,
    title: str,
    objective: str,
    explanation: str,
    key_points: tuple[str, str, str],
    example_steps: tuple[tuple[str, str], tuple[str, str], tuple[str, str]],
    practice_title: str,
    practice_prompt: str,
    keywords: tuple[str, ...],
    hints: tuple[str, str, str],
) -> dict:
    if not 3 <= len(keywords) <= 5:
        raise ValueError(f'Lesson "{title}" must have from 3 to 5 practice keywords.')
    if any(keyword != keyword.lower() for keyword in keywords):
        raise ValueError(f'Lesson "{title}" has a non-lowercase practice keyword.')
    normalized_prompt = practice_prompt.lower()
    if any(keyword not in normalized_prompt for keyword in keywords):
        raise ValueError(f'Lesson "{title}" does not explicitly request every practice keyword.')

    return {
        "title": title,
        "objective": objective,
        "explanation": explanation,
        "key_points": list(key_points),
        "example_steps": [
            {"title": step_title, "text": step_text}
            for step_title, step_text in example_steps
        ],
        "practice": {
            "kind": "text",
            "title": practice_title,
            "prompt": practice_prompt,
            "keywords": list(keywords),
            "hints": list(hints),
        },
    }


